// Refresh approved operator copy and byte-bound metadata after reviewing source diffs.
import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
import {loadCatalog} from './site-test-harness.mjs';
const specs=JSON.parse(fs.readFileSync('operator-card-specs.json','utf8'));
const context={window:{}};vm.runInNewContext(fs.readFileSync('catalog-data.js','utf8'),context);
const alignment=JSON.parse(fs.readFileSync('docs/qa/OPERATOR-SCRIPT-ALIGNMENT.json','utf8'));
const byFile=new Map(alignment.map(x=>[x.file,x]));
const originalContext={window:{}};vm.runInNewContext(fs.readFileSync('card-guidance.js','utf8'),originalContext);
const reviews=originalContext.window.FIELD_KIT_CARD_GUIDANCE;
const connectionContext={window:{}};vm.runInNewContext(fs.readFileSync('connection-guidance.js','utf8'),connectionContext);
const connections=connectionContext.window.FIELD_KIT_CONNECTION_GUIDANCE;
const changed=[];
const effective=loadCatalog(process.cwd()).api.ITEMS.filter(item=>item.publishedPath);
for(const item of effective){
 const row=byFile.get(item.file);
 const sha=crypto.createHash('sha256').update(fs.readFileSync(item.publishedPath)).digest('hex');
 if(reviews[item.file])reviews[item.file].sourceSha256=sha;
 if(connections[item.publishedPath])connections[item.publishedPath].sha256=sha;
 if(row?.changed && item.verification && !row.priorVerification)row.priorVerification=item.verification;
 if(specs[item.file])Object.assign(specs[item.file],{sourceSha256:sha,presentationRevision:Boolean(row?.changed),releaseVersion:row?.version||item.version||''});
}

for(const item of context.window.CATALOG_DATA){
 if(!item.publishedPath)continue;
 const sha=crypto.createHash('sha256').update(fs.readFileSync(item.publishedPath)).digest('hex');
 if(reviews[item.file])reviews[item.file].sourceSha256=sha;
 if(connections[item.publishedPath])connections[item.publishedPath].sha256=sha;
 const row=byFile.get(item.file);
 if(row?.changed){
  if(item.verification){row.priorVerification=item.verification;delete item.verification;}
  item.version=row.version;changed.push(item.file);
 }
 if(specs[item.file]&&reviews[item.file]){
  // Concrete ID-vs-domain preparation must remain visible before launch.
  if(/Tenant ID \(GUID\)/i.test(reviews[item.file].input||'')) { const value=specs[item.file].input;specs[item.file].input=specs[item.file].scope==='TENANT'?'Tenant ID':/tenant ID/i.test(value)?value:value+' + tenant ID'; }
 }
}
const old=fs.readFileSync('card-guidance.js','utf8');
const marker='window.FIELD_KIT_CARD_GUIDANCE = Object.freeze(';
const a=old.indexOf(marker)+marker.length,b=old.indexOf('\n});',a)+2;
let copy=old.slice(0,a)+JSON.stringify(reviews,null,2)+old.slice(b);
const opMarker='\n// Approved compact operator cards.';
if(copy.includes(opMarker))copy=copy.slice(0,copy.indexOf(opMarker));
copy+=opMarker+' Generated from operator-card-specs.json.\nwindow.FIELD_KIT_OPERATOR_CARDS = Object.freeze('+JSON.stringify(specs,null,2)+');\n';
fs.writeFileSync('card-guidance.js',copy);
fs.writeFileSync('connection-guidance.js','// Reviewed connection behavior; bound to exact downloadable source bytes.\nwindow.FIELD_KIT_CONNECTION_GUIDANCE = Object.freeze('+JSON.stringify(connections,null,2)+');\n');
fs.writeFileSync('catalog-data.js','window.CATALOG_DATA = '+JSON.stringify(context.window.CATALOG_DATA,null,2)+';\n');
fs.writeFileSync('operator-card-specs.json',JSON.stringify(specs,null,2)+'\n');
fs.writeFileSync('docs/qa/OPERATOR-SCRIPT-ALIGNMENT.json',JSON.stringify(alignment,null,2)+'\n');
console.log(`Approved operator copy: ${Object.keys(specs).length}; presentation revisions: ${alignment.filter(x=>x.changed).length}`);

const manifestContext={window:{}};vm.runInNewContext(fs.readFileSync('source-integrity.js','utf8'),manifestContext);
const hashes=Object.fromEntries(Object.keys(manifestContext.window.FIELD_KIT_SOURCE_INTEGRITY).sort((a,b)=>a.localeCompare(b)).map(p=>[p,crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex')]));
fs.writeFileSync('source-integrity.js','// Generated by node tools/check-site.mjs --write-integrity. Do not edit by hand.\nwindow.FIELD_KIT_SOURCE_INTEGRITY = Object.freeze('+JSON.stringify(hashes,null,2)+');\n');
