// Run: node tools/check-site.mjs [--write-integrity]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { loadCatalog } from './site-test-harness.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const {api,window}=loadCatalog(root);
const hashes={};
for(const item of api.ITEMS){
  if(!item.publishedPath)continue;
  const value=item.publishedPath;
  assert.match(value,/^(?:published-source\/|tools\/|toys\/|OPERATING-STANDARDS\.md$)/,`Source outside approved directories: ${value}`);
  assert.match(value,/^[a-z0-9._/-]+\.(?:ps1|md)$/i,`Unexpected source path: ${value}`);
  assert(!value.split('/').some(part=>!part||part==='.'||part==='..'),`Unsafe path: ${value}`);
  const diskPath=path.resolve(root,value);
  assert(diskPath.startsWith(root+path.sep),`Source escaped repository: ${value}`);
  assert(!fs.lstatSync(diskPath).isSymbolicLink(),`Symlink source is not allowed: ${value}`);
  assert(fs.statSync(diskPath).isFile(),`Missing source file: ${value}`);
  const bytes=fs.readFileSync(diskPath);
  assert(bytes.length>0&&bytes.length<=2*1024*1024,`Invalid source size: ${value}`);
  const text=new TextDecoder('utf-8',{fatal:true,ignoreBOM:true}).decode(bytes);
  assert(Buffer.from(text,'utf8').equals(bytes),`Source must round-trip without changing encoding: ${value}`);
  assert(!/^\s*(?:<!doctype\s+html|<html\b)/i.test(bytes.toString('utf8')),`Source is an HTML page: ${value}`);
  assert.equal(path.extname(item.file).toLowerCase(),path.extname(value).toLowerCase(),`Download extension mismatch: ${value}`);
  hashes[value]=crypto.createHash('sha256').update(bytes).digest('hex');
}
// Unlinked files in a public repository are still public. Only these build wrappers are intentionally uncatalogued.
const wrappers=new Set(['tools/export-field-kit.ps1','tools/handoff.ps1']);
const tracked=execFileSync('git',['ls-files','-z'],{cwd:root,encoding:'utf8'}).split('\0').filter(Boolean);
const privateMaterial=/\.(?:pfx|p12|key|kdbx)$/i;
const secretPatterns=[/-----BEGIN (?:RSA |EC |OPENSSH |ENCRYPTED )?PRIVATE KEY-----/,
  /\bgh[pousr]_[a-zA-Z0-9]{30,}\b/,/\bgithub_pat_[a-zA-Z0-9_]{50,}\b/,/\bAKIA[A-Z0-9]{16}\b/,
  /\bAIza[0-9A-Za-z_-]{35}\b/];
for(const value of tracked){
  assert(!privateMaterial.test(value),`Private credential container must not be published: ${value}`);
  const content=fs.readFileSync(path.join(root,value),'utf8');
  for(const pattern of secretPatterns)assert(!pattern.test(content),`Possible exposed credential in ${value}; review before publishing`);
  if(/^(?:published-source|tools|toys)\/.*\.ps1$/i.test(value)){
    assert(hashes[value]||wrappers.has(value),`Uncatalogued PowerShell source requires explicit release review: ${value}`);
  }
}
const sorted=Object.fromEntries(Object.entries(hashes).sort(([a],[b])=>a.localeCompare(b)));
const manifest='// Generated by node tools/check-site.mjs --write-integrity. Do not edit by hand.\nwindow.FIELD_KIT_SOURCE_INTEGRITY = Object.freeze('+JSON.stringify(sorted,null,2)+');\n';
if(process.argv.includes('--write-integrity'))fs.writeFileSync(path.join(root,'source-integrity.js'),manifest);
else assert.equal(fs.readFileSync(path.join(root,'source-integrity.js'),'utf8'),manifest,'Source checksums are stale. Review source changes, then run node tools/check-site.mjs --write-integrity');
window.FIELD_KIT_SOURCE_INTEGRITY=sorted;
assert.equal(api.runFrameworkAudit().ok,true,'Catalog framework audit failed');
for(const name of ['index.html','concept-neon-mint-reference.html']){
  const html=fs.readFileSync(path.join(root,name),'utf8');
  assert(html.includes('name="referrer" content="no-referrer"'),`${name}: missing referrer policy`);
  for(const directive of ["script-src 'self'","script-src-attr 'none'","object-src 'none'","base-uri 'none'","form-action 'none'"]){
    assert(html.includes(directive),`${name}: missing CSP ${directive}`);
  }
  assert(!/<script(?![^>]*\bsrc=)[^>]*>[\s\S]*?\S[\s\S]*?<\/script>/i.test(html),`${name}: inline script`);
  assert(!/\son[a-z]+\s*=/i.test(html),`${name}: inline event handler`);
  assert(html.indexOf('source-integrity.js')<html.indexOf('field-kit-app.js'),`${name}: checksum manifest loads too late`);
  for(const [,src]of html.matchAll(/<script[^>]*src="([^"]+)"/g)){
    assert(!src.includes('..')&&!src.includes(':'),`${name}: unexpected script origin`);
    assert(fs.existsSync(path.join(root,src)),`${name}: missing script ${src}`);
  }
  assert(html.includes('aria-label="Search all catalog sections"'),`${name}: search needs an accessible label`);
  assert(/aria-hidden="true" inert/.test(html),`${name}: closed drawer must be inert`);
}
console.log(`PASS: ${api.ITEMS.length} catalog items; ${Object.keys(sorted).length} downloadable sources; checksums, paths, policy and markup.`);
